import { readdirSync, statSync } from "node:fs";
import path from "node:path";
import { readLibraryRecords, type LibraryRecord } from "./libraryLog.js";
import { resolveFolderMap, type TargetInfo } from "./targets.js";
import type { AppConfig } from "./config.js";

export interface LibraryEntry {
  /** Folder name relative to the target's romRoot, e.g. "ps2". */
  folder: string;
  filename: string;
  /** Absolute path on the destination. */
  fullPath: string;
  sizeBytes: number;
  modifiedAt: string;
  /** The system this folder is mapped to, or null when the folder isn't mapped to one. */
  systemId: string | null;
  /** Populated from data/library.jsonl when this app wrote the file; null for anything it didn't. */
  record: LibraryRecord | null;
}

export interface LibrarySystemGroup {
  systemId: string | null;
  folder: string;
  entries: LibraryEntry[];
  totalBytes: number;
}

export interface LibraryIndex {
  targetName: string;
  romRoot: string;
  groups: LibrarySystemGroup[];
  fileCount: number;
  totalBytes: number;
  freeBytes: number | null;
}

/**
 * Files that live alongside ROMs but aren't games. Playlists are generated by this
 * app, and the dot-prefixed files are macOS metadata that exFAT volumes collect —
 * listing either as library entries would be noise the user can't act on.
 */
function isLibraryFile(name: string): boolean {
  return !name.startsWith(".") && !name.toLowerCase().endsWith(".m3u");
}

/**
 * Builds a view of what is actually on a destination.
 *
 * The card is the source of truth, not the processing log: files put there by another
 * tool, or by an earlier install of this app, are just as real as ones it wrote. The
 * log only enriches what the scan finds — hashes, DAT match, original name — joined on
 * the destination path.
 *
 * One level deep per system folder. Nothing here recurses into subdirectories, since a
 * ROM sitting two levels down isn't something the rest of the app can address either.
 */
export function buildLibraryIndex(target: TargetInfo, config: AppConfig): LibraryIndex {
  const { folderMap } = resolveFolderMap(target, config);
  const systemIdByFolder = new Map(Object.entries(folderMap).map(([systemId, folder]) => [folder, systemId] as const));

  const recordsByDestination = new Map<string, LibraryRecord>();
  for (const record of readLibraryRecords()) {
    // Later records win: re-processing a file to the same destination should surface
    // the run that produced what's actually sitting there now.
    recordsByDestination.set(record.destination, record);
  }

  const groups: LibrarySystemGroup[] = [];
  let fileCount = 0;
  let totalBytes = 0;

  for (const folder of target.folders) {
    const folderPath = path.join(target.romRoot, folder);
    let names: string[];
    try {
      names = readdirSync(folderPath, { withFileTypes: true })
        .filter((entry) => entry.isFile() && isLibraryFile(entry.name))
        .map((entry) => entry.name);
    } catch {
      continue; // unreadable folder — skip it rather than failing the whole index
    }
    if (names.length === 0) continue;

    const entries: LibraryEntry[] = [];
    let groupBytes = 0;

    for (const filename of names.sort((a, b) => a.localeCompare(b))) {
      const fullPath = path.join(folderPath, filename);
      let stat;
      try {
        stat = statSync(fullPath);
      } catch {
        continue; // vanished between readdir and stat
      }

      entries.push({
        folder,
        filename,
        fullPath,
        sizeBytes: stat.size,
        modifiedAt: stat.mtime.toISOString(),
        systemId: systemIdByFolder.get(folder) ?? null,
        record: recordsByDestination.get(fullPath) ?? null,
      });
      groupBytes += stat.size;
    }

    if (entries.length === 0) continue;
    groups.push({ systemId: systemIdByFolder.get(folder) ?? null, folder, entries, totalBytes: groupBytes });
    fileCount += entries.length;
    totalBytes += groupBytes;
  }

  // Mapped systems first (alphabetically by folder), then unmapped folders — the
  // latter are the ones needing attention, so they read as a distinct tail section
  // rather than being scattered through the list.
  groups.sort((a, b) => {
    if ((a.systemId === null) !== (b.systemId === null)) return a.systemId === null ? 1 : -1;
    return a.folder.localeCompare(b.folder);
  });

  return {
    targetName: target.name,
    romRoot: target.romRoot,
    groups,
    fileCount,
    totalBytes,
    freeBytes: target.freeBytes,
  };
}
